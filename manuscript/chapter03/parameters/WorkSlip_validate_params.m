function valid=WorkSlip_validate_params(P)
%#codegen
% 中文注释永久保留：后续修改代码时不得删除注释，只能根据代码更新修改注释表述。
% 参数加载和运行均检查；无效时由监督器保护，禁止静默 NaN 求逆。
valid=all(isfinite(P.work_J_wheel)) && all(P.work_J_wheel>0) && ...
 all(isfinite(P.R)) && all(P.R>0) && all(isfinite(P.work_R)) && ...
 all(abs(P.work_R-P.R)<1e-10) && abs(P.Ts-.001)<1e-12 && ...
 all(isfinite(P.kappa_set)) && P.work_tau_slip>P.Ts && ...
 P.work_tau_d>P.Ts && P.work_tau_ref>P.Ts && ...
 all(isfinite(P.work_a_min)) && all(P.work_a_min>0) && ...
 all(isfinite(P.work_k)) && all(P.work_k>=0) && ...
 all(isfinite(P.work_eta)) && all(P.work_eta>=0) && ...
 all(isfinite(P.work_phi)) && all(P.work_phi>0) && ...
 all(P.work_proj_weight>0) && all(isfinite(P.work_proj_weight));
end
