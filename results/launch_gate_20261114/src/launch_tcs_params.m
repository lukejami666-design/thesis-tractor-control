function P = launch_tcs_params()
%--------------------------------------------------------------------------
% 文件名称：
%   launch_tcs_params.m
%
% 文件功能：
%   集中定义起步防滑控制器所需的全部参数。
%
% 使用方法：
%   在 MATLAB 命令行或模型初始化脚本中执行：
%
%       P = launch_tcs_params();
%
%   然后在 Simulink 的 MATLAB Function 模块中，将 P 设置为：
%
%       Scope: Parameter
%
% 四轮顺序：
%   P(1) = FL，左前轮
%   P(2) = FR，右前轮
%   P(3) = RL，左后轮
%   P(4) = RR，右后轮
%
% 注意：
%   本文件中的数值为第一版联合仿真初值，不是最终标定值。
%   后续应根据正常起步、重载起步、单轮空转和多轮空转波形进一步调整。
%--------------------------------------------------------------------------


%% 1. 基本采样时间
% Simulink 和 TruckSim 当前采用 1 ms 固定步长。
%
% 所有时间累计、离散积分、扭矩变化率限制和动态参数更新，
% 均基于该采样周期。
P.Ts = 0.001;


%% 2. 整车几何参数

%--------------------------------------------------------------------------
% 2.1 四个车轮的有效滚动半径
%
% 单位：m。
%
% 轮端角速度乘以有效滚动半径后，
% 可得到车轮理论轮面线速度：
%
%       v_wheel_i = R_i * omega_i
%--------------------------------------------------------------------------
P.R = [ ...
     0.834;    % FL
     0.834;    % FR
     0.940;    % RL
     0.940];   % RR


%--------------------------------------------------------------------------
% 2.2 四个车轮相对于整车质心的纵向坐标
%
% 单位：m。
%
% 约定：
%   车辆前进方向为正；
%   质心前方的车轮坐标为正；
%   质心后方的车轮坐标为负。
%--------------------------------------------------------------------------
P.x = [ ...
     2.043;    % FL
     2.043;    % FR
    -1.362;    % RL
    -1.362];   % RR


%--------------------------------------------------------------------------
% 2.3 四个车轮相对于整车质心的横向坐标
%
% 单位：m。
%
% 约定：
%   车辆左侧为正；
%   车辆右侧为负。
%
% 前轮距约为 2.390 m，半轮距约为 1.195 m；
% 后轮距约为 2.330 m，半轮距约为 1.165 m。
%--------------------------------------------------------------------------
P.y = [ ...
     1.195;    % FL
    -1.195;    % FR
     1.165;    % RL
    -1.165];   % RR


%% 3. 一阶低通滤波器参数

%--------------------------------------------------------------------------
% 控制器不直接使用原始轮速、车速、加速度和横摆角速度信号。
%
% 离散一阶滤波器为：
%
%       x_f(k) = (1-alpha)*x_f(k-1) + alpha*x(k)
%
% 其中：
%
%       alpha = Ts / (tau + Ts)
%
% tau 越小：
%   响应越快，但噪声抑制能力越弱；
%
% tau 越大：
%   信号越平滑，但空转检测和保护响应会变慢。
%--------------------------------------------------------------------------

% 轮速滤波时间常数：20 ms。
P.alpha_w = P.Ts / (0.020 + P.Ts);

% 纵向车速滤波时间常数：50 ms。
P.alpha_v = P.Ts / (0.050 + P.Ts);

% 横向车速滤波时间常数：50 ms。
P.alpha_vy = P.Ts / (0.050 + P.Ts);

% 纵向加速度滤波时间常数：50 ms。
P.alpha_a = P.Ts / (0.050 + P.Ts);

% 横摆角速度滤波时间常数：50 ms。
P.alpha_r = P.Ts / (0.050 + P.Ts);


%% 4. 默认轮端最大扭矩

%--------------------------------------------------------------------------
% 本节必须位于低速闭环增益计算之前。
%
% 原代码在前面使用了：
%
%       P.TcapDefault
%       P.TcapFloor
%
% 但这两个字段在原代码末尾才创建，
% 因此 MATLAB 执行到低速闭环参数时会报：
%
%       无法识别的字段名称 "TcapDefault"
%
% 现在提前定义这两个字段，后续即可正常使用。
%
% 注意：
%   TcapDefault 是临时或默认轮端能力上限；
%   正式仿真时，LaunchTCS_Torque 仍优先使用动态输入 T_max。
%--------------------------------------------------------------------------

%--------------------------------------------------------------------------
% 4.1 前、后电机峰值扭矩
%
% 单位：N·m。
%
% 这里的数值是根据当前电机特性图提取的初始峰值。
% 如果模型中的电机特性模块已经直接输出动态轮端能力 TMax，
% 则这些参数仅用于初始化 Kp_dv，不作为最终动态限幅。
%--------------------------------------------------------------------------
front_peak_motor = 1100;
rear_peak_motor  = 1800;


%--------------------------------------------------------------------------
% 4.2 前、后传动系统减速比
%--------------------------------------------------------------------------
front_ratio = 63.52;
rear_ratio  = 80.4536;


%--------------------------------------------------------------------------
% 4.3 轴端扭矩到左右轮端扭矩的分配系数
%
% 当前假设：
%   front_peak_motor 和 rear_peak_motor 表示轴端总电机扭矩；
%   前、后轴扭矩平均分配到左右两个车轮；
%   因此 axle_split = 2。
%
% 如果电机特性图中的峰值扭矩已经是单轮电机扭矩，
% 则应将 axle_split 修改为 1。
%--------------------------------------------------------------------------
axle_split = 2;


%--------------------------------------------------------------------------
% 4.4 默认轮端扭矩能力上限
%
% 计算关系：
%
%       T_wheel_max =
%           T_motor_max * gear_ratio / axle_split
%
% 四轮顺序：
%   FL、FR、RL、RR
%--------------------------------------------------------------------------
P.TcapDefault = [ ...
    front_peak_motor * front_ratio / axle_split;   % FL
    front_peak_motor * front_ratio / axle_split;   % FR
    rear_peak_motor  * rear_ratio  / axle_split;   % RL
    rear_peak_motor  * rear_ratio  / axle_split];  % RR


%--------------------------------------------------------------------------
% 4.5 扭矩能力最小保护值
%
% 当动态输入 T_max 小于该值，或者 T_max 为 NaN/Inf 时，
% LaunchTCS_Torque 将该车轮视为当前不可用，并令其能力为 0。
%--------------------------------------------------------------------------
P.TcapFloor = [ ...
    1;    % FL
    1;    % FR
    1];   % RL
% 注意：这里需要四个车轮，下面立即修正为四维向量。
P.TcapFloor = [ ...
    1;    % FL
    1;    % FR
    1;    % RL
    1];   % RR


%% 5. 车速信号可信性参数

%--------------------------------------------------------------------------
% 车速合理范围，单位：m/s。
%
% 当前控制器主要考虑前进工况。
% vx_min 设置为小的负值，用于容许传感器噪声或数值误差。
%--------------------------------------------------------------------------
P.vx_min = -0.5;
P.vx_max = 20.0;


%--------------------------------------------------------------------------
% 进入正常作业过程滑转控制的车速阈值，单位：m/s。
%
% 当车速超过该值，并持续满足信号可信条件时，
% 状态机才允许从起步防滑阶段进入正常作业阶段。
%--------------------------------------------------------------------------
P.v_valid_on = 1.50;


%--------------------------------------------------------------------------
% 正常作业阶段退出阈值，单位：m/s。
%
% 采用速度滞环：
%
%       进入正常作业：vx >= v_valid_on
%       退出正常作业：vx <  v_valid_off
%
% 这样可以避免车速在临界值附近波动导致状态频繁切换。
%--------------------------------------------------------------------------
P.v_valid_off = 1.00;


%--------------------------------------------------------------------------
% 车速进入可信状态所需的持续时间，单位：s。
%--------------------------------------------------------------------------
P.t_speed_on = 0.15;


%--------------------------------------------------------------------------
% 车速可信状态失效所需的持续时间，单位：s。
%--------------------------------------------------------------------------
P.t_speed_off = 0.10;


%% 6. 车速与加速度一致性参数

%--------------------------------------------------------------------------
% 车速微分值与纵向加速度之间允许的最大差异，单位：m/s^2。
%
% 控制器计算：
%
%       vx_dot = (vx(k)-vx(k-1))/Ts
%
% 并判断：
%
%       abs(vx_dot - ax)
%
% 是否超过该阈值。
%--------------------------------------------------------------------------
P.a_cons_max = 3.0;


%--------------------------------------------------------------------------
% 车速—加速度一致性异常持续时间，单位：s。
%
% 超过该时间后，状态机可以进入保护状态。
%--------------------------------------------------------------------------
P.t_cons_bad = 0.20;


%% 7. 起步运动判别参数

%--------------------------------------------------------------------------
% 判断车体已经开始有效运动的车速阈值，单位：m/s。
%--------------------------------------------------------------------------
P.v_move_on = 0.25;


%--------------------------------------------------------------------------
% 判断车轮是否已经具有足够运动速度，单位：m/s。
%
% 该参数用于避免车辆静止时轮速测量噪声触发空转判定。
%--------------------------------------------------------------------------
P.v_wheel_min = 0.30;


%--------------------------------------------------------------------------
% 判断车辆是否产生有效纵向响应的加速度阈值，单位：m/s^2。
%--------------------------------------------------------------------------
P.a_response = 0.20;


%--------------------------------------------------------------------------
% 判断车轮空转时车体纵向加速度较小的阈值，单位：m/s^2。
%
% 如果轮端速度快速升高，而车体加速度仍较小，
% 则更可能是轮端空转，而不是正常加速。
%--------------------------------------------------------------------------
P.a_spin_max = 0.20;


%--------------------------------------------------------------------------
% 进入重载未起动状态所使用的持续时间，单位：s。
%--------------------------------------------------------------------------
P.t_no_move = 0.80;


%% 8. 轮端—车体速度差空转判别参数

%--------------------------------------------------------------------------
% 空转进入阈值，单位：m/s。
%
% 定义：
%
%       dv_i = R_i*omega_i - v_ref_i
%
% 当 dv_i 长时间超过该值时，
% 认为第 i 个车轮可能出现持续空转。
%--------------------------------------------------------------------------
P.dv_spin_on = 0.80;


%--------------------------------------------------------------------------
% 空转解除阈值，单位：m/s。
%
% 采用：
%
%       dv_spin_off < dv_spin_on
%
% 形成滞环，避免速度差在临界值附近波动时反复进入和退出空转。
%--------------------------------------------------------------------------
P.dv_spin_off = 0.40;


%--------------------------------------------------------------------------
% 空转速度差增长率阈值，单位：m/s^2。
%
% 当 dv 正在快速增加时，
% 即使车体加速度略高于 a_spin_max，
% 也允许触发空转判别。
%--------------------------------------------------------------------------
P.dv_growth_on = 3.0;


%--------------------------------------------------------------------------
% 空转进入确认时间，单位：s。
%--------------------------------------------------------------------------
P.t_spin_on = 0.08;


%--------------------------------------------------------------------------
% 空转解除确认时间，单位：s。
%--------------------------------------------------------------------------
P.t_spin_clear = 0.25;


%% 9. 低速归一化滑转速度差闭环参数

%--------------------------------------------------------------------------
% 本节用于第二天加入的低速起步闭环。
%
% 控制量定义：
%
%       dv_i = R_i*omega_i - v_ref_i
%
%       dv_norm_i = max(dv_i,0) / dv_ctrl_scale
%
% 闭环误差：
%
%       e_i = dv_norm_i - dv_ref_norm
%
% 当 e_i > 0 时，说明轮端速度差超过目标，
% 控制器对对应车轮进行削扭。
%--------------------------------------------------------------------------


%--------------------------------------------------------------------------
% 9.1 归一化尺度
%
% 单位：m/s。
%
% 初始使用空转触发阈值作为速度差归一化尺度。
% 这样 dv 达到空转触发阈值时，
% 对应的无量纲速度差大约为 1。
%--------------------------------------------------------------------------
P.dv_ctrl_scale = max(P.dv_spin_on, 0.10);


%--------------------------------------------------------------------------
% 9.2 低速闭环目标速度差
%
% 单位：m/s。
%
% 初始取空转解除阈值和进入阈值的中间值：
%
%       dv_ctrl_ref =
%           0.5*(dv_spin_on + dv_spin_off)
%
% 这样闭环会先于 Stateflow 的空转锁存动作开始削扭。
%--------------------------------------------------------------------------
P.dv_ctrl_ref = 0.5 * ...
    (P.dv_spin_on + P.dv_spin_off);


%--------------------------------------------------------------------------
% 9.3 速度差控制死区
%
% 单位：m/s。
%
% 当归一化速度差误差处于死区内时，
% 比例积分反馈不动作，避免在目标附近高频抖动。
%--------------------------------------------------------------------------
P.dv_ctrl_deadband = ...
    0.05 * P.dv_ctrl_scale;


%--------------------------------------------------------------------------
% 9.4 归一化速度差最大保护值
%
% 防止轮速传感器瞬时异常造成过大的反馈削扭。
%--------------------------------------------------------------------------
P.dv_ctrl_max_norm = 2.0;


%--------------------------------------------------------------------------
% 9.5 初始比例增益
%
% 先根据默认轮端能力上限构造一个初始比例增益。
%
% e_test 表示从闭环目标到空转触发阈值之间的归一化误差。
% 当 e_test 对应速度差达到空转触发阈值附近时，
% 比例反馈削减约为轮端能力的 15%。
%
% 该增益单位为 N·m。
%--------------------------------------------------------------------------
Tcap0 = max( ...
    P.TcapDefault(:), ...
    P.TcapFloor(:));

e_test = max( ...
    (P.dv_spin_on - P.dv_ctrl_ref) / ...
    P.dv_ctrl_scale, ...
    0.10);

P.Kp_dv = ...
    0.15 * Tcap0 / e_test;


%--------------------------------------------------------------------------
% 9.6 初始积分增益
%
% 第一轮仿真先关闭积分，只验证比例反馈方向和稳定性。
%
% P.Ki_dv 的单位为 N·m/s。
% 后续如果出现明显稳态速度差，
% 再根据实际波形逐步增加积分增益。
%--------------------------------------------------------------------------
P.Ki_dv = zeros(4,1);


%--------------------------------------------------------------------------
% 9.7 积分项最大值
%
% 这里表示积分削扭量不超过当前轮端能力的 50%。
%--------------------------------------------------------------------------
P.dv_int_max_frac = 0.50;


%--------------------------------------------------------------------------
% 9.8 最大闭环削扭量
%
% 这里设置为当前轮端能力的 100%。
% 但在 LaunchTCS_Torque 中还会进一步限制：
%
%       cut_max <= T_pref_open
%
% 因此闭环不会产生负扭矩。
%--------------------------------------------------------------------------
P.dv_cut_max_frac = 1.00;


%--------------------------------------------------------------------------
% 9.9 参数关系检查
%
% 目标速度差应位于空转解除阈值和空转进入阈值之间。
%--------------------------------------------------------------------------
if ~(P.dv_spin_off < P.dv_ctrl_ref && ...
        P.dv_ctrl_ref < P.dv_spin_on)

    error([ ...
        '低速闭环参数错误：必须满足 ', ...
        'dv_spin_off < dv_ctrl_ref < dv_spin_on']);
end


%% Day2 second-round smooth launch optimization: selected refine03, 10s verified
P.Kp_dv_base = [26202; 26202; 54306.18; 54306.18];
P.Kp_dv_scale = 2.00;
P.Kp_dv = P.Kp_dv_scale * P.Kp_dv_base;
P.Ki_dv = zeros(4,1);
P.tau_dv_ctrl = 0.005;
P.tau_q_work_release = 0.75;
P.tau_cut_on = 0.003;
P.tau_cut_release = 0.10;
P.dv_ctrl_ref = P.dv_spin_off + 0.30 * (P.dv_spin_on - P.dv_spin_off);
P.dv_ctrl_deadband = 0.05 * (P.dv_spin_on - P.dv_spin_off);
P.dv_work_guard = 0.65;
P.t_spin_on = 0.08;
P.t_spin_clear = 0.25;
P.t_stage3_min = 0.15;
P.t_stage4_min = 0.15;
if ~(P.dv_spin_off < P.dv_ctrl_ref && P.dv_ctrl_ref < P.dv_spin_on)
    error('Require dv_spin_off < dv_ctrl_ref < dv_spin_on');
end
assert(all(P.Ki_dv == 0), 'Integral feedback must remain disabled');
assert(P.dv_work_guard > P.dv_ctrl_ref, 'Work guard must exceed dv reference');


%% 10. 有效驱动扭矩判别参数

%--------------------------------------------------------------------------
% 判断车轮是否处于有效驱动状态的扭矩比例阈值。
%
% 当实际扭矩或上一拍控制扭矩超过：
%
%       applied_active_frac * T_cap_i
%
% 才认为该车轮正在被主动驱动。
%
% 如果没有实际电机反馈，
% T_actual 可以使用 T_cmd 的 Unit Delay。
%--------------------------------------------------------------------------
P.applied_active_frac = 0.02;


%% 11. 起步扭矩探测比例

%--------------------------------------------------------------------------
% 起步初始扭矩比例。
%
% 起步时不直接施加全部基础扭矩，
% 而是从较小扭矩开始逐步探测当前路面和负载的可承受能力。
%--------------------------------------------------------------------------
P.q_start = 0.05;


%--------------------------------------------------------------------------
% 正常起步时扭矩探测比例增加速率，单位：1/s。
%--------------------------------------------------------------------------
P.q_probe_rate = 0.15;


%--------------------------------------------------------------------------
% 重载未起动状态下允许的最大扭矩比例。
%
% 车辆没有有效前进时，
% 不允许无限制增加扭矩。
%--------------------------------------------------------------------------
P.q_no_move_max = 0.25;


%--------------------------------------------------------------------------
% 重载未起动状态下扭矩探测比例增加速率，单位：1/s。
%--------------------------------------------------------------------------
P.q_no_move_rate = 0.02;


%--------------------------------------------------------------------------
% 检测到单轮或多轮空转后，
% 扭矩探测比例下降速率，单位：1/s。
%--------------------------------------------------------------------------
P.q_spin_down = 0.10;


%% 12. 多轮空转时的总扭矩比例

%--------------------------------------------------------------------------
% 多轮空转时允许保留的最小总扭矩比例。
%
% 不将总扭矩直接降为零，
% 是为了保留一定起步能力和脱困能力。
%--------------------------------------------------------------------------
P.q_multi_min = 0.45;


%--------------------------------------------------------------------------
% 多轮空转时总扭矩比例下降速率，单位：1/s。
%--------------------------------------------------------------------------
P.q_multi_cut_rate = 1.00;


%--------------------------------------------------------------------------
% 多轮空转解除后的总扭矩比例恢复速率，单位：1/s。
%--------------------------------------------------------------------------
P.q_multi_rec_rate = 0.15;


%% 13. 单轮运行扭矩上限更新参数

%--------------------------------------------------------------------------
% 单轮运行扭矩上限的最低比例。
%
% 即使某个车轮持续空转，
% 也暂时保留一定的最小扭矩能力。
%--------------------------------------------------------------------------
P.q_limit_floor = 0.15;


%--------------------------------------------------------------------------
% 单轮空转时运行扭矩上限下降速率，单位：1/s。
%--------------------------------------------------------------------------
P.q_limit_cut_rate = 1.50;


%--------------------------------------------------------------------------
% 空转解除后运行扭矩上限恢复速率，单位：1/s。
%--------------------------------------------------------------------------
P.q_limit_rec_rate = 0.25;


%% 14. 传感器异常保护参数

%--------------------------------------------------------------------------
% 进入保护状态时默认保留的扭矩比例。
%--------------------------------------------------------------------------
P.q_protect = 0.10;


%--------------------------------------------------------------------------
% 传感器异常时保护扭矩下降速率，单位：1/s。
%--------------------------------------------------------------------------
P.q_protect_down = 1.00;


%% 15. 控制扭矩变化率限制

%--------------------------------------------------------------------------
% 扭矩上升变化率比例，单位：1/s。
%
% 实际每个车轮允许的上升量为：
%
%       Delta_T_rise_i =
%           cmd_rise_rate * T_cap_i * Ts
%
% 当前设置为：
%   每秒最多增加当前能力上限的 5%。
%--------------------------------------------------------------------------
P.cmd_rise_rate = 0.25;


%--------------------------------------------------------------------------
% 扭矩下降变化率比例，单位：1/s。
%
% 实际每个车轮允许的下降量为：
%
%       Delta_T_fall_i =
%           cmd_fall_rate * T_cap_i * Ts
%
% 下降速率通常设置得大于上升速率，
% 以便发生空转时及时降低扭矩。
%--------------------------------------------------------------------------
P.cmd_fall_rate = 12.00;


% 2026-11-11 loaded-launch selection: Ki=0; current motor cap unchanged.
% Scenario: D0=10000 N, B=1000 N*s/m, C=2800 N*s^2/m^2; ramp 0.4 s.
% Parametric load assumption, not identified ASABE coefficients.
% See 工作记录/2026-11-11/有载起步优化 for raw trials and tradeoffs.

%% 16. 最终参数尺寸检查

%--------------------------------------------------------------------------
% 检查四轮参数是否均为 4×1 列向量。
