function P = launch_tcs_params()
%--------------------------------------------------------------------------
% 文件名称：
%   launch_tcs_params.m
%
% 文件功能：
%   集中定义起步防滑控制器 LaunchTCS_Core 所需的全部参数。
%
% 使用方法：
%   在 MATLAB 命令行或模型初始化脚本中执行：
%
%       P = launch_tcs_params();
%
%   然后在 Simulink 的 MATLAB Function 模块中，将 P 设置为：
%
%       Scope: Parameter
%
%   注意：
%   本参数文件中的数值是第一版联合仿真初值，不是最终标定值。
%   后续应根据正常起步、重载起步、单轮低附着和多轮低附着波形进行调整。
%
% 四轮顺序：
%   P(1) = FL，左前轮
%   P(2) = FR，右前轮
%   P(3) = RL，左后轮
%   P(4) = RR，右后轮
%--------------------------------------------------------------------------

%% 1. 基本采样时间

% Simulink 和 TruckSim 当前采用 1 ms 固定步长。
% 因此控制器内部的时间累计、滤波器和变化率限制都基于该采样周期。
P.Ts = 0.001;


%% 2. 整车几何参数

% 四个车轮的有效滚动半径，单位：m。
%
% 前轮滚动半径约为 0.834 m；
% 后轮滚动半径约为 0.940 m。
%
% 轮端角速度乘以滚动半径后，可得到轮胎理论纵向线速度：
%
%       v_wheel = R_i * omega_i
%
P.R = [0.834;    % FL
       0.834;    % FR
       0.940;    % RL
       0.940];   % RR

% 四个车轮相对于整车质心的纵向坐标，单位：m。
%
% 约定：
%   向前为正；
%   质心前方的前轮坐标为正；
%   质心后方的后轮坐标为负。
%
P.x = [ 2.043;   % FL
        2.043;   % FR
       -1.362;   % RL
       -1.362];  % RR

% 四个车轮相对于整车质心的横向坐标，单位：m。
%
% 约定：
%   左侧为正；
%   右侧为负。
%
% 前轮距约为 2.390 m，因此半轮距约为 1.195 m；
% 后轮距约为 2.330 m，因此半轮距约为 1.165 m。
%
P.y = [ 1.195;   % FL
       -1.195;   % FR
        1.165;   % RL
       -1.165];  % RR


%% 3. 一阶低通滤波器参数

% 控制器不直接使用原始轮速、车速和加速度信号。
% 这里使用离散一阶滤波器：
%
%       x_f(k) = (1-alpha)*x_f(k-1) + alpha*x(k)
%
% 其中：
%
%       alpha = Ts / (tau + Ts)
%
% tau 越小，滤波响应越快，但对噪声的抑制能力越弱；
% tau 越大，信号越平滑，但空转检测延迟会增加。

% 轮速滤波时间常数：20 ms。
P.alpha_w = P.Ts / (0.020 + P.Ts);

% 纵向车速滤波时间常数：50 ms。
P.alpha_v = P.Ts / (0.050 + P.Ts);

% 横向车速滤波时间常数：50 ms。
P.alpha_vy = P.Ts / (0.050 + P.Ts);

% 纵向加速度滤波时间常数：50 ms。
P.alpha_a = P.Ts / (0.050 + P.Ts);

% 横摆角速度滤波时间常数：50 ms。
P.alpha_r = P.Ts / (0.050 + P.Ts);


%% 4. 车速信号可信性参数

% 车速合理范围，单位：m/s。
%
% 当前控制器只考虑前进工况，因此 vx_min 允许一个小的负值，
% 用于容许传感器噪声或数值误差。
P.vx_min = -0.5;
P.vx_max = 20.0;

% 进入正常作业过程滑转控制的车速阈值，单位：m/s。
%
% 当车速超过该值，并且持续满足信号可信条件时，
% 才允许从起步防滑阶段进入作业过程阶段。
P.v_valid_on = 1.50;

% 作业阶段退出阈值，单位：m/s。
%
% 采用滞环设计：
%
%       进入作业阶段：vx >= v_valid_on
%       退出作业阶段：vx <  v_valid_off
%
% 这样可以避免车速在临界值附近波动导致状态频繁切换。
P.v_valid_off = 1.00;

% 车速进入可信状态所需的持续时间，单位：s。
P.t_speed_on = 0.15;

% 车速可信状态失效所需的持续时间，单位：s。
P.t_speed_off = 0.10;


%% 5. 车速与加速度一致性参数

% 车速微分值与实测纵向加速度之间允许的最大差异，单位：m/s^2。
%
% 控制器计算：
%
%       vx_dot = (vx(k)-vx(k-1))/Ts
%
% 然后比较：
%
%       abs(vx_dot - ax)
%
% 如果长期超过该阈值，说明车速信号、加速度信号或同步关系可能异常。
P.a_cons_max = 3.0;

% 车速—加速度一致性异常持续时间，单位：s。
% 超过该时间后，控制器进入保护状态。
P.t_cons_bad = 0.20;


%% 6. 起步运动判别参数

% 判断车体已经开始有效运动的车速阈值，单位：m/s。
P.v_move_on = 0.25;

% 判断车轮是否至少已经具有一定运动速度，单位：m/s。
% 该参数用于避免静止时轮速噪声触发空转判定。
P.v_wheel_min = 0.30;

% 判断车辆是否已经产生有效纵向响应的加速度阈值，单位：m/s^2。
P.a_response = 0.20;

% 判断车轮空转时车体纵向加速度较小的阈值，单位：m/s^2。
%
% 如果轮端速度快速升高，而车体加速度仍小于该值，
% 则更可能是轮端空转而不是正常加速。
P.a_spin_max = 0.20;

% 进入重载未起动状态所使用的持续时间，单位：s。
P.t_no_move = 0.80;


%% 7. 轮端—车体速度差空转判别参数

% 空转进入阈值，单位：m/s。
%
% 定义：
%
%       dv_i = R_i * omega_i - v_ref_i
%
% 如果 dv_i 长时间超过该值，则认为车轮可能出现持续空转。
P.dv_spin_on = 0.80;

% 空转解除阈值，单位：m/s。
%
% 采用：
%
%       dv_spin_off < dv_spin_on
%
% 形成滞环，避免 dv 在临界值附近波动时反复进入和退出空转状态。
P.dv_spin_off = 0.40;

% 空转速度差增长率阈值，单位：m/s^2。
%
% 当车轮速度差正在快速增大时，即使车体加速度略高于
% a_spin_max，也允许触发空转判别。
P.dv_growth_on = 3.0;

% 空转进入确认时间，单位：s。
%
% 单个采样点满足空转条件不能立即判定空转，
% 必须持续满足 t_spin_on 后才置位空转锁存标志。
P.t_spin_on = 0.08;

% 空转解除确认时间，单位：s。
%
% 只有 dv 持续低于解除阈值达到该时间后，
% 才解除对应车轮的空转锁存状态。
P.t_spin_clear = 0.15;


%% 8. 有效驱动扭矩判别参数

% 判断车轮是否处于有效驱动状态的扭矩比例阈值。
%
% 当实际扭矩或上一拍控制扭矩超过：
%
%       applied_active_frac * T_cap_i
%
% 才认为该车轮正在被主动驱动。
%
% 如果没有实际电机反馈，则 T_actual 可以使用 T_cmd 的 Unit Delay。
P.applied_active_frac = 0.02;


%% 9. 起步扭矩探测比例

% 起步初始扭矩比例。
%
% 起步控制初始不直接施加全部基础扭矩，
% 而是从较小扭矩开始逐步探测当前路面和负载的可承受能力。
P.q_start = 0.05;

% 正常起步时扭矩探测比例的增加速率，单位：1/s。
P.q_probe_rate = 0.30;

% 重载未起动状态下允许的最大扭矩比例。
%
% 车辆没有有效前进时，不允许无限制增加扭矩。
P.q_no_move_max = 0.25;

% 重载未起动状态下扭矩探测比例的增加速率，单位：1/s。
P.q_no_move_rate = 0.02;

% 检测到单轮或多轮空转后，扭矩探测比例的下降速率，单位：1/s。
P.q_spin_down = 0.50;


%% 10. 多轮空转时的总扭矩比例

% 多轮空转时允许保留的最小总扭矩比例。
%
% 不将总扭矩直接降为零，是为了保留一定的起步能力。
P.q_multi_min = 0.45;

% 多轮空转时总扭矩比例下降速率，单位：1/s。
P.q_multi_cut_rate = 1.00;

% 多轮空转解除后的总扭矩恢复速率，单位：1/s。
P.q_multi_rec_rate = 0.15;


%% 11. 单轮运行扭矩上限更新参数

% 单轮运行上限的最低比例。
%
% 即使某个车轮持续空转，也暂时保留一定的最小扭矩能力。
P.q_limit_floor = 0.15;

% 单轮空转时运行扭矩上限下降速率，单位：1/s。
P.q_limit_cut_rate = 1.50;

% 空转解除后运行扭矩上限恢复速率，单位：1/s。
P.q_limit_rec_rate = 0.25;


%% 12. 传感器异常保护参数

% 进入保护状态时，默认保留的扭矩比例。
P.q_protect = 0.10;

% 传感器异常时保护扭矩的下降速率，单位：1/s。
P.q_protect_down = 1.00;


%% 13. 控制扭矩变化率限制

% 扭矩上升变化率比例，单位：1/s。
%
% 实际每个车轮允许的上升量为：
%
%       cmd_rise_rate * T_cap_i * Ts
P.cmd_rise_rate = 1.00;

% 扭矩下降变化率比例，单位：1/s。
%
% 下降通常允许比上升更快，以便在发生空转时及时降扭。
P.cmd_fall_rate = 3.00;


%% 14. 默认轮端最大扭矩

% 以下参数用于在没有连接现有电机特性曲线时，
% 为控制器提供临时的轮端扭矩上限。
%
% 注意：
%   这些数值只是初始估算值。
%   最终应优先使用现有模型中“前电机特性图1”和“后电机特性图1”
%   计算得到的实际轮端扭矩上限。
%
% 当前电机峰值扭矩：
%   前电机：1100 N·m
%   后电机：1800 N·m
front_peak_motor = 1100;
rear_peak_motor  = 1800;

% 前、后减速器速比。
front_ratio = 63.52;
rear_ratio  = 80.4536;

% 当前假定前、后轴的电机扭矩平均分配到左右两个车轮。
%
% 如果模型中的峰值扭矩本身已经是单轮电机扭矩，
% 则需要将 axle_split 改为 1。
axle_split = 2;

% 根据电机轴端峰值扭矩和减速比，得到轮端临时扭矩上限。
%
% 计算关系：
%
%       T_wheel = T_motor * gear_ratio / axle_split
%
P.TcapDefault = [ ...
    front_peak_motor * front_ratio / axle_split;  % FL
    front_peak_motor * front_ratio / axle_split;  % FR
    rear_peak_motor  * rear_ratio  / axle_split;  % RL
    rear_peak_motor  * rear_ratio  / axle_split];% RR

% 扭矩上限的最小保护值，单位：N·m。
% 用于防止 T_cap 为零、负数、NaN 或 Inf 时造成异常。
P.TcapFloor = [1; 1; 1; 1];

end